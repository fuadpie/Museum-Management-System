-- Museum & Art Gallery Visitor Portal
-- Run this script once in the Oracle schema used by backend/.env.

CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(120) NOT NULL,
    EMAIL VARCHAR2(255) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    PHONE VARCHAR2(30),
    BIRTH_DATE DATE,
    CITY VARCHAR2(100),
    COUNTRY VARCHAR2(100),
    INTERESTS VARCHAR2(500),
    ROLE VARCHAR2(20) DEFAULT 'USER' NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT USERS_ROLE_CK CHECK (ROLE IN ('USER', 'STAFF', 'ADMIN', 'MUSEUM_MANAGER')),
    CONSTRAINT USERS_STATUS_CK CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE MUSEUMS (
    MUSEUM_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OWNER_USER_ID NUMBER REFERENCES USERS(USER_ID),
    NAME VARCHAR2(180) NOT NULL,
    LOCATION VARCHAR2(180) NOT NULL,
    DESCRIPTION VARCHAR2(2000),
    PHONE VARCHAR2(30),
    EMAIL VARCHAR2(255),
    WEBSITE_URL VARCHAR2(500),
    OPENING_TIME VARCHAR2(20),
    CLOSING_TIME VARCHAR2(20),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT MUSEUMS_STATUS_CK CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE EXHIBITIONS (
    EXHIBITION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MUSEUM_ID NUMBER NOT NULL REFERENCES MUSEUMS(MUSEUM_ID),
    TITLE VARCHAR2(180) NOT NULL,
    DESCRIPTION VARCHAR2(2000),
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,
    TICKET_PRICE NUMBER(10,2) DEFAULT 0 NOT NULL,
    COVER_IMAGE VARCHAR2(1000),
    STATUS VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT EXHIBITIONS_DATES_CK CHECK (END_DATE >= START_DATE),
    CONSTRAINT EXHIBITIONS_STATUS_CK CHECK (STATUS IN ('OPEN', 'CLOSED', 'CANCELLED'))
);

CREATE TABLE ARTWORKS (
    ARTWORK_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EXHIBITION_ID NUMBER NOT NULL REFERENCES EXHIBITIONS(EXHIBITION_ID),
    TITLE VARCHAR2(180) NOT NULL,
    ARTIST_NAME VARCHAR2(180) NOT NULL,
    CREATION_YEAR NUMBER(4),
    CATEGORY VARCHAR2(100),
    DESCRIPTION VARCHAR2(2000),
    IMAGE_URL VARCHAR2(1000),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE TICKETS (
    TICKET_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID),
    EXHIBITION_ID NUMBER NOT NULL REFERENCES EXHIBITIONS(EXHIBITION_ID),
    VISIT_DATE DATE NOT NULL,
    PRICE NUMBER(10,2) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    BOOKED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT TICKETS_STATUS_CK CHECK (STATUS IN ('PENDING', 'CONFIRMED', 'CANCELLED'))
);

CREATE TABLE PAYMENTS (
    PAYMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TICKET_ID NUMBER NOT NULL REFERENCES TICKETS(TICKET_ID),
    AMOUNT NUMBER(10,2) NOT NULL,
    PAYMENT_METHOD VARCHAR2(30) NOT NULL,
    TRANSACTION_ID VARCHAR2(120) NOT NULL UNIQUE,
    PAYMENT_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    CONSTRAINT PAYMENTS_STATUS_CK CHECK (STATUS IN ('PROCESSING', 'SUCCESS', 'FAILED'))
);

CREATE TABLE REVIEWS (
    REVIEW_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID),
    MUSEUM_ID NUMBER NOT NULL REFERENCES MUSEUMS(MUSEUM_ID),
    RATING NUMBER(1) NOT NULL,
    REVIEW_TEXT VARCHAR2(2000) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT REVIEWS_RATING_CK CHECK (RATING BETWEEN 1 AND 5)
);

CREATE INDEX EXHIBITIONS_MUSEUM_IDX ON EXHIBITIONS(MUSEUM_ID);
CREATE INDEX ARTWORKS_EXHIBITION_IDX ON ARTWORKS(EXHIBITION_ID);
CREATE INDEX TICKETS_USER_IDX ON TICKETS(USER_ID);
CREATE INDEX REVIEWS_MUSEUM_IDX ON REVIEWS(MUSEUM_ID);

